/** Generates supabase/seed_problems.sql from the content bank (trusted problem ratings for server-side Elo). */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import type { Problem } from '../src/content/types';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(ROOT, 'src/content/problems');
const problems: Problem[] = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts'))) {
  const m = await import(pathToFileURL(join(dir, f)).href);
  problems.push(...m.default);
}
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = problems.map((p) => `  (${q(p.id)}, ${p.level}, ${p.rating}, ${q(p.title)}, ${p.stages.length})`);
const sql = `-- Generated by \`npm run gen:seed\`. Re-run after adding or editing problems.
insert into public.problems (id, level, rating, title, stages) values
${rows.join(',\n')}
on conflict (id) do update set level = excluded.level, rating = excluded.rating, title = excluded.title, stages = excluded.stages;
`;
writeFileSync(join(ROOT, 'supabase/seed_problems.sql'), sql);
console.log(`Wrote ${problems.length} problems to supabase/seed_problems.sql`);
